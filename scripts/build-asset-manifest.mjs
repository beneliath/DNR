import {createHash} from 'node:crypto';
import {readdir, readFile, writeFile} from 'node:fs/promises';
import {join, relative, sep} from 'node:path';

const sourceRoot = 'src';
const assetRoot = join(sourceRoot, 'assets');
const outputPath = join(assetRoot, 'asset-manifest.php');

async function assetFiles(directory) {
    const entries = await readdir(directory, {withFileTypes: true});
    const nested = await Promise.all(entries.map(async (entry) => {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) return assetFiles(path);
        return entry.isFile() && path !== outputPath ? [path] : [];
    }));
    return nested.flat();
}

const fingerprints = [];
for (const path of (await assetFiles(assetRoot)).sort()) {
    const contents = await readFile(path);
    const publicPath = relative(sourceRoot, path).split(sep).join('/');
    const hash = createHash('sha256').update(contents).digest('hex').slice(0, 12);
    fingerprints.push(`    ${JSON.stringify(publicPath)} => ${JSON.stringify(hash)},`);
}

const generated = [
    '<?php',
    '',
    '// Generated by scripts/build-asset-manifest.mjs; do not edit by hand.',
    'return [',
    ...fingerprints,
    '];',
    '',
].join('\n');

await writeFile(outputPath, generated, 'utf8');
